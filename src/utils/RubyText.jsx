const SORTED_KEYS = Object.keys(KANJI_RUBY_MAP).sort((a, b) => b.length - a.length);
const KANJI_REGEX = new RegExp(`(${SORTED_KEYS.join('|')})`, 'g');

/**
 * RubyText Component
 * Renders Japanese sentences with authentic HTML <ruby> and <rt> tags
 * displaying Furigana directly above the Kanji, matching Minna no Nihongo textbook style.
 */
export default function RubyText({ text, className = '' }) {
  if (!text) return null;
  if (!/[\u4e00-\u9faf]/.test(text)) {
    return <span className={className}>{text}</span>;
  }

  const parts = [];
  let lastIndex = 0;
  let match;
  let idx = 0;

  KANJI_REGEX.lastIndex = 0;

  while ((match = KANJI_REGEX.exec(text)) !== null) {
    if (match.index > lastIndex) {
      parts.push(text.slice(lastIndex, match.index));
    }
    const matchedKanji = match[0];
    const furigana = KANJI_RUBY_MAP[matchedKanji];
    parts.push(
      <ruby key={idx++}>
        {matchedKanji}
        <rt>{furigana}</rt>
      </ruby>
    );
    lastIndex = KANJI_REGEX.lastIndex;
  }
  if (lastIndex < text.length) {
    parts.push(text.slice(lastIndex));
  }

  return <span className={`ruby-sentence ${className}`}>{parts}</span>;
}
